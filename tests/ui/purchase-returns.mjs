import { chromium } from "playwright";
import { B } from "../lib/harness.mjs";
const out = process.argv[2];
const ok = (c, m) => { if (!c) { console.log("  ✗", m); process.exitCode = 1; } else console.log("  ✓", m); };
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, timezoneId: "Asia/Karachi" });
const page = await ctx.newPage();
const errors = []; page.on("pageerror", (e) => errors.push(e.message));
let native = 0; page.on("dialog", (d) => { native++; d.dismiss(); });
const post = (path, body) => page.evaluate(async ([p, b]) => (await fetch(p, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(b) })).json(), [path, body]);
await page.goto(B + "/setup");
await post("/api/setup", { name: "Admin", username: "admin", password: "admin-pass-123" });
await post("/api/auth/login", { username: "admin", password: "admin-pass-123" });
await post("/api/admin/tenants", { shopName: "UI Mart", shopType: "general", maxUsers: 3, ownerName: "Sana", username: "sana", password: "secret1" });
await post("/api/auth/logout", {});
await page.goto(B + "/login");
await page.fill('input[autocomplete="username"]', "sana");
await page.fill('input[type="password"]', "secret1");
await page.click('button[type="submit"]');
await page.waitForURL(B + "/");
const rice = await post("/api/products", { name: "Rice", unit: "kg", costPrice: 200, salePrice: 250, lowStockAlert: 1 });
const oil = await post("/api/products", { name: "Oil", unit: "pcs", costPrice: 500, salePrice: 600, lowStockAlert: 1 });
const sup = await post("/api/parties", { type: "supplier", name: "Distributor" });
const p1 = await post("/api/purchases", { supplierId: sup._id, amountPaid: 0, supplierInvoice: "D-77", items: [{ productId: rice._id, qty: 10, cost: 200 }, { productId: oil._id, qty: 4, cost: 500 }] });
const p2 = await post("/api/purchases", { supplierId: sup._id, amountPaid: 0, items: [{ productId: oil._id, qty: 1, cost: 500 }] });

await page.goto(B + "/purchases");
await page.waitForSelector(`text=${p1.purchaseNo}`);
await page.click(`tr:has-text('${p1.purchaseNo}') button:has-text('Open')`);
const dlg = page.locator("[role=dialog]");
await dlg.waitFor();
await page.waitForSelector("[role=dialog] >> text=Rice");
ok((await dlg.innerText()).includes("Inv D-77"), "purchase details open");
await dlg.locator("button:has-text('Return to supplier')").click();
await dlg.locator("li:has-text('Oil') button[aria-label=More]").click();
await dlg.locator("li:has-text('Oil') button[aria-label=More]").click();
await dlg.locator("input[aria-label='Quantity of Rice to return']").fill("1.5");
ok(await dlg.locator("button:has-text('Return Rs 1,300')").count() === 1, "return value 2 oil + 1.5 kg rice = 1,300");
await page.screenshot({ path: `${out}/purchase-return.png` });
await dlg.locator("button:has-text('Return Rs 1,300')").click();
await page.waitForSelector("text=taken off the supplier's khata");
await page.waitForTimeout(400);
ok((await dlg.innerText()).includes("Part returned") && (await dlg.innerText()).includes("PRN-000001"), "purchase shows part returned and the return");
await page.keyboard.press("Escape");
await page.waitForTimeout(300);
ok((await page.locator(`tr:has-text('${p1.purchaseNo}')`).innerText()).includes("returned"), "list shows returned amount");
await page.click("button:has-text('Returns to suppliers')");
await page.waitForSelector("text=PRN-000001");
ok((await page.locator("tbody").innerText()).includes("Less in khata"), "returns tab lists it");
const bal = await page.evaluate(async (id) => (await (await fetch(`/api/parties/${id}`)).json()).party.balance, sup._id);
ok(bal === 4500 - 1300, `supplier khata reduced (${bal})`);
// cancel the second purchase
await page.click("button:has-text('Purchases')");
await page.click(`tr:has-text('${p2.purchaseNo}') button:has-text('Open')`);
await page.waitForSelector("[role=dialog] >> text=Cancel purchase");
await dlg.locator("button:has-text('Cancel purchase')").click();
await page.waitForSelector("[role=alertdialog]");
ok((await page.locator("[role=alertdialog]").innerText()).includes(`Cancel purchase ${p2.purchaseNo}?`), "cancel asks for confirmation");
await page.screenshot({ path: `${out}/purchase-cancel.png` });
await page.click("[role=alertdialog] button:has-text('Cancel purchase')");
await page.waitForSelector("text=Purchase cancelled");
await page.keyboard.press("Escape");
await page.waitForTimeout(400);
ok((await page.locator(`tr:has-text('${p2.purchaseNo}')`).innerText()).includes("Cancelled"), "list shows Cancelled");
await page.setViewportSize({ width: 390, height: 844 });
await page.goto(B + "/purchases");
await page.waitForSelector(`text=${p1.purchaseNo}`);
ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), "purchases page fits a phone");
ok(native === 0, "no browser pop-ups");
ok(errors.length === 0, "no page errors " + JSON.stringify(errors));
await browser.close();
