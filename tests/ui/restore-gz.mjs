import { chromium } from "playwright";
import { gzipSync } from "zlib";
import { writeFileSync } from "fs";
import { B } from "../lib/harness.mjs";
const out = process.argv[2];
const ok = (c, m) => { if (!c) { console.log("  ✗", m); process.exitCode = 1; } else console.log("  ✓", m); };
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined });
const page = await (await browser.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
const errors = []; page.on("pageerror", (e) => errors.push(e.message));
const post = (path, body) => page.evaluate(async ([p, b]) => (await fetch(p, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(b) })).json(), [path, body]);
await page.goto(B + "/setup");
await post("/api/setup", { name: "Admin", username: "admin", password: "admin-pass-123" });
await post("/api/auth/login", { username: "admin", password: "admin-pass-123" });
await post("/api/admin/tenants", { shopName: "GZ Mart", shopType: "general", maxUsers: 3, ownerName: "Sana", username: "sana", password: "secret1" });
await post("/api/auth/logout", {});
await page.goto(B + "/login");
await page.fill('input[autocomplete="username"]', "sana");
await page.fill('input[type="password"]', "secret1");
await page.click('button[type="submit"]');
await page.waitForURL(B + "/");
await post("/api/products", { name: "Soap", unit: "pcs", costPrice: 80, salePrice: 100, lowStockAlert: 1, openingStock: 5 });
const backup = await page.evaluate(async () => (await fetch("/api/backup")).json());
const file = `${out}/gz-mart.json.gz`;
writeFileSync(file, gzipSync(JSON.stringify(backup)));
await page.goto(B + "/settings");
await page.waitForSelector("text=Restore from backup");
await page.setInputFiles("input[type=file][accept*='gz']", file);
await page.waitForSelector("[role=dialog] >> text=GZ Mart");
ok((await page.locator("[role=dialog]").innerText()).includes("Products"), "compressed automatic backup opens in the restore screen");
await page.screenshot({ path: `${out}/gz-restore.png` });
ok(errors.length === 0, "no page errors " + JSON.stringify(errors));
await browser.close();
