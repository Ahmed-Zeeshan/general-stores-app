import { chromium } from "playwright";
import { B, norm } from "../lib/harness.mjs";
const out = process.argv[2];
const ok = (c, m) => { if (!c) { console.log("  ✗", m); process.exitCode = 1; } else console.log("  ✓", m); };
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, timezoneId: "Asia/Karachi" });
let nativeDialogs = 0;
page.on("dialog", (d) => { nativeDialogs++; d.dismiss(); });
const errors = []; page.on("pageerror", (e) => errors.push(e.message));
await page.goto(B + "/login");
await page.fill('input[autocomplete="username"]', "ahmed");
await page.fill('input[type="password"]', "secret1");
await page.click('button[type="submit"]');
await page.waitForURL(B + "/");
// make a JazzCash bill
const r = await page.evaluate(async () => {
  const p = await (await fetch("/api/products?q=Olpers")).json();
  return (await fetch("/api/sales", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ items: [{ productId: p[0]._id, qty: 2 }], paymentMethod: "jazzcash" }) })).json();
});
await page.goto(B + "/sales");
await page.waitForSelector(`text=${r.invoiceNo}`);
await page.click(`tr:has-text('${r.invoiceNo}') button:has-text('Return')`);
await page.waitForSelector("[role=dialog]");
await page.waitForTimeout(300);
let text = await page.locator("[role=dialog]").innerText().then(norm);
ok(text.includes(`Return items — ${r.invoiceNo}`) && text.includes("JazzCash"), "return screen shows bill and payment method");
await page.keyboard.press("Escape");
await page.waitForTimeout(300);
ok(await page.locator("[role=dialog]").count() === 0, "Escape closes without returning");
ok(await page.locator(`tr:has-text('${r.invoiceNo}') >> text=Returned`).count() === 0, "bill not returned after cancel");
await page.click(`tr:has-text('${r.invoiceNo}') button:has-text('Return')`);
await page.click("[role=dialog] button:has-text('Cancel')");
await page.waitForTimeout(300);
ok(await page.locator("[role=dialog]").count() === 0, "Cancel closes");
await page.click(`tr:has-text('${r.invoiceNo}') button:has-text('Return')`);
await page.click("[role=dialog] button:has-text('Return everything')");
await page.screenshot({ path: `${out}/confirm-return.png` });
await page.click(`[role=dialog] button:has-text("Return & refund Rs ${r.total.toLocaleString("en-US")}")`);
await page.waitForSelector("text=Return saved");
ok((await page.locator("[role=dialog]").innerText().then(norm)).includes("Give back to customer (JazzCash)"), "refund to JazzCash by default");
await page.click("[role=dialog] button:has-text('Done')");
await page.waitForTimeout(500);
ok(await page.locator(`tr:has-text('${r.invoiceNo}') >> text=Returned`).count() === 1, "bill returned");
// product remove dialog
await page.goto(B + "/products");
await page.waitForSelector("tr:has-text('Sugar')");
await page.locator("tr:has-text('Sugar') button[aria-label='More actions']").click();
await page.click("text='Remove'");
await page.waitForSelector("[role=alertdialog]");
await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/confirm-delete.png` });
ok((await page.locator("[role=alertdialog]").innerText().then(norm)).includes('Remove "Sugar"?'), "remove product dialog");
await page.click("[role=alertdialog] button:has-text('Cancel')");
ok(nativeDialogs === 0, "no browser pop-ups used");
console.log("page errors:", JSON.stringify(errors));
await browser.close();
