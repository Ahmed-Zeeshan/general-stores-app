import { chromium } from "playwright";
import { B } from "../lib/harness.mjs";
const out = process.argv[2];
const ok = (c, m) => { if (!c) { console.log("  ✗", m); process.exitCode = 1; } else console.log("  ✓", m); };
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, timezoneId: "Asia/Karachi" });
const page = await ctx.newPage();
const errors = []; page.on("pageerror", (e) => errors.push(e.message));
const post = (path, body) => page.evaluate(async ([p, b]) => (await fetch(p, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(b) })).json(), [path, body]);
await page.goto(B + "/setup");
await post("/api/setup", { name: "Admin", username: "admin", password: "admin-pass-123" });
await post("/api/auth/login", { username: "admin", password: "admin-pass-123" });
await post("/api/admin/tenants", { shopName: "UI Mart", shopType: "general", maxUsers: 3, ownerName: "Sana", username: "sana", password: "secret1" });
await post("/api/auth/logout", {});
await page.goto(B + "/login");
await page.fill('input[autocomplete="username"]', "sana");
await page.fill('input[type="password"]', "secret1");
await page.click('button[type="submit"]');
await page.waitForURL(B + "/");
await post("/api/products", { name: "Ghee 1kg", unit: "pcs", costPrice: 600, salePrice: 800, lowStockAlert: 1, openingStock: 50 });

await page.goto(B + "/pos");
await page.click("button:has-text('Ghee 1kg')");
await page.click("text=Take Payment");
const dlg = page.locator("[role=dialog]");
await dlg.waitFor();
await dlg.locator("button:has-text('Split payment')").click();
await dlg.locator("input[aria-label='JazzCash amount']").fill("300");
await dlg.locator("div:has(> input[aria-label='Cash amount']) button:has-text('Rest')").click();
ok((await dlg.locator("input[aria-label='Cash amount']").inputValue()) === "500", "Rest fills cash with 500");
await page.screenshot({ path: `${out}/split-pos.png` });
await dlg.locator("input[aria-label='Cash amount']").fill("1000");
let t = (await dlg.innerText()).replace(/\n/g, " ");
ok(/Change to return\s*Rs 500/.test(t), "cash over → change 500");
await dlg.locator("input[aria-label='JazzCash amount']").fill("900");
t = await dlg.innerText();
ok(t.includes("add up to more than the bill") && (await dlg.locator("button:has-text('Confirm & Save Bill')").isDisabled()), "non-cash over the bill → error, cannot save");
await dlg.locator("input[aria-label='JazzCash amount']").fill("300");
await dlg.locator("input[aria-label='Cash amount']").fill("200");
t = (await dlg.innerText()).replace(/\n/g, " ");
ok(/Goes to udhaar\s*Rs 300/.test(t) && (await dlg.locator("button:has-text('Confirm & Save Bill')").isDisabled()), "short → udhaar needs a customer");
await dlg.locator("input[aria-label='Cash amount']").fill("1000");
await dlg.locator("button:has-text('Confirm & Save Bill')").click();
await page.waitForSelector("text=Bill saved");
ok((await page.locator("[role=dialog]").innerText()).includes("Rs 500"), "bill saved, change 500 shown");
const [rp] = await Promise.all([page.waitForEvent("popup"), page.click("[role=dialog] button:has-text('Print')")]);
await rp.waitForSelector("text=TOTAL");
const rt = await rp.innerText("body");
ok(rt.includes("JazzCash") && /Cash\s+Rs 1,000/.test(rt) && /Change\s+Rs 500/.test(rt), "receipt lists JazzCash, cash given and change");
await rp.screenshot({ path: `${out}/split-receipt.png`, fullPage: true });
await rp.close();
await page.goto(B + "/sales");
await page.waitForSelector("text=Split:");
ok(true, "sales list shows Split badge");
// single method with transaction id
await page.goto(B + "/pos");
await page.click("button:has-text('Ghee 1kg')");
await page.click("text=Take Payment");
await dlg.waitFor();
await dlg.locator("button:has-text('Easypaisa')").click();
await dlg.locator("input[aria-label='Transaction ID']").fill("EP-4455");
await dlg.locator("button:has-text('Confirm & Save Bill')").click();
await page.waitForSelector("text=Bill saved");
const last = await page.evaluate(async () => (await (await fetch("/api/sales")).json())[0]);
ok(last.payments?.[0]?.ref === "EP-4455" && last.paymentMethod === "easypaisa", "Easypaisa transaction ID saved");
await page.setViewportSize({ width: 390, height: 844 });
await page.goto(B + "/pos");
await page.click("button:has-text('Ghee 1kg')");
await page.locator("text=Take Payment").last().click();
await dlg.waitFor();
await dlg.locator("button:has-text('Split payment')").click();
await page.waitForTimeout(300);
ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), "split screen fits a phone");
await page.screenshot({ path: `${out}/split-mobile.png` });
ok(errors.length === 0, "no page errors " + JSON.stringify(errors));
await browser.close();
