import { chromium } from "playwright";
import { B } from "../lib/harness.mjs";
const out = process.argv[2];
const ok = (c, m) => { if (!c) { console.log("  ✗", m); process.exitCode = 1; } else console.log("  ✓", m); };
const day = (n) => new Date(Date.now() + n * 864e5).toISOString().slice(0, 10);
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, timezoneId: "Asia/Karachi" });
const page = await ctx.newPage();
const errors = []; page.on("pageerror", (e) => errors.push(e.message));
let native = 0; page.on("dialog", (d) => { native++; d.dismiss(); });
const post = (path, body) => page.evaluate(async ([p, b]) => (await fetch(p, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(b) })).json(), [path, body]);
await page.goto(B + "/setup");
await post("/api/setup", { name: "Admin", username: "admin", password: "admin-pass-123" });
await post("/api/auth/login", { username: "admin", password: "admin-pass-123" });
await post("/api/admin/tenants", { shopName: "UI Mart", shopType: "general", maxUsers: 3, ownerName: "Sana", username: "sana", password: "secret1" });
await post("/api/auth/logout", {});
await page.goto(B + "/login");
await page.fill('input[autocomplete="username"]', "sana");
await page.fill('input[type="password"]', "secret1");
await page.click('button[type="submit"]');
await page.waitForURL(B + "/");

await page.goto(B + "/products");
await page.click("button:has-text('Add product')");
await page.fill('input[placeholder^="e.g. Sugar"]', "Yogurt 500g");
const form = page.locator("#product-form");
await form.locator("input[placeholder='0']").nth(0).fill("120");
await form.locator("input[placeholder='0']").nth(1).fill("150");
await form.locator("input[aria-label='Track expiry by batch']").check();
await form.locator("input[aria-label='Shelf life days']").fill("7");
await form.locator("input[placeholder='0']").nth(2).fill("6");
await form.locator("input[aria-label='Opening stock expiry']").fill(day(-1));
await page.screenshot({ path: `${out}/expiry-form.png` });
await page.click("button:has-text('Add product') >> nth=-1");
await page.waitForSelector("text=Product added");
const prod = await page.evaluate(async () => (await (await fetch("/api/products?q=Yogurt")).json())[0]);
ok(prod.trackExpiry && prod.shelfLifeDays === 7 && prod.stock === 6, "tracked product created with 6 in stock");

await page.goto(B + "/purchases/new");
await page.fill("input[placeholder='Search product or scan barcode to add']", "Yogurt");
await page.click("ul button:has-text('Yogurt 500g')");
await page.locator("tbody input[type=number]").first().fill("24");
await page.fill("input[aria-label='Expiry of Yogurt 500g']", day(10));
await page.fill("input[aria-label='Batch number of Yogurt 500g']", "Y-10");
await page.click("button:has-text('Save purchase')");
await page.waitForURL(/\/purchases$/);
ok(true, "purchase with expiry date saved");

await page.goto(B + "/expiry");
await page.waitForSelector("text=Yogurt 500g");
let t = await page.locator("tbody").innerText();
ok(t.includes("Expired yesterday") && t.includes("Batch Y-10") && t.includes("In 10 days") || t.includes("In 9 days"), "expiry report shows expired lot and the new batch");
await page.screenshot({ path: `${out}/expiry-report.png` });
await page.click("tr:has-text('Expired') button:has-text('Write off')");
await page.waitForSelector("[role=alertdialog]");
await page.click("[role=alertdialog] button:has-text('Write off')");
await page.waitForSelector("text=written off");
await page.waitForTimeout(600);
t = await page.locator("body").innerText();
ok(!t.includes("Expired yesterday"), "expired lot gone after write-off");
const st = await page.evaluate(async (id) => (await (await fetch(`/api/products/${id}`)).json()).product.stock, prod._id);
ok(st === 24, `stock now 24 (${st})`);
await page.setViewportSize({ width: 390, height: 844 });
await page.goto(B + "/expiry");
await page.waitForTimeout(800);
ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), "expiry page fits a phone");
ok(native === 0, "no browser pop-ups");
ok(errors.length === 0, "no page errors " + JSON.stringify(errors));
await browser.close();
