import { chromium } from "playwright";
import { B } from "../lib/harness.mjs";
const out = process.argv[2];
const ok = (c, m) => { if (!c) { console.log("  ✗", m); process.exitCode = 1; } else console.log("  ✓", m); };
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, timezoneId: "Asia/Karachi" });
const page = await ctx.newPage();
const errors = []; page.on("pageerror", (e) => errors.push(e.message));
const post = (path, body) => page.evaluate(async ([p, b]) => (await fetch(p, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(b) })).json(), [path, body]);
await page.goto(B + "/setup");
await post("/api/setup", { name: "Admin", username: "admin", password: "admin-pass-123" });
await post("/api/auth/login", { username: "admin", password: "admin-pass-123" });
await post("/api/admin/tenants", { shopName: "UI Mart", shopType: "general", maxUsers: 3, ownerName: "Sana", username: "sana", password: "secret1" });
await post("/api/auth/logout", {});
await page.goto(B + "/login");
await page.click("button:has-text('اردو')");
await page.waitForSelector("text=خوش آمدید");
ok(await page.locator("button:has-text('لاگ ان')").count() === 1, "login page in Urdu");
await page.screenshot({ path: `${out}/ur-login.png` });
await page.fill('input[autocomplete="username"]', "sana");
await page.fill('input[type="password"]', "secret1");
await page.click('button[type="submit"]');
await page.waitForURL(B + "/");
await post("/api/products", { name: "Lux Soap", unit: "pcs", costPrice: 80, salePrice: 100, lowStockAlert: 1, openingStock: 100 });
await page.goto(B + "/pos");
await page.waitForSelector("text=نیا بل");
await page.click("button:has-text('Lux Soap')");
const t = await page.locator("body").innerText();
ok(t.includes("بل کی اشیاء") && t.includes("رقم وصول کریں") && t.includes("ٹوٹل") && t.includes("Rs 100"), "POS in Urdu, amounts in digits");
ok((await page.locator("nav").innerText()).includes("کھاتہ"), "menu in Urdu");
await page.screenshot({ path: `${out}/ur-pos.png` });
await page.click("button:has-text('رقم وصول کریں')");
await page.waitForSelector("text=کل ادائیگی");
await page.screenshot({ path: `${out}/ur-pay.png` });
await page.click("[role=dialog] button:has-text('بل محفوظ کریں')");
await page.waitForSelector("text=بل محفوظ ہو گیا");
ok(true, "bill saved in Urdu mode");
await page.keyboard.press("Escape");
await page.reload();
await page.waitForSelector("text=نیا بل");
ok(true, "language remembered after reload");
await page.click("nav >> xpath=.. >> button:has-text('English')");
await page.waitForSelector("text=New Bill");
ok(true, "switch back to English");
await page.setViewportSize({ width: 390, height: 844 });
await page.click("button:has-text('Lux Soap')").catch(() => {});
await page.evaluate(() => localStorage.setItem("dukaan:lang", "ur"));
await page.reload();
await page.waitForTimeout(1500);
ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), "Urdu POS fits a phone");
await page.screenshot({ path: `${out}/ur-mobile.png` });
ok(errors.length === 0, "no page errors " + JSON.stringify(errors));
await browser.close();
