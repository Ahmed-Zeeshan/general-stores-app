import { chromium } from "playwright";
import { B } from "../lib/harness.mjs";
const out = process.argv[2];
const ok = (c, m) => { if (!c) { console.log("  ✗", m); process.exitCode = 1; } else console.log("  ✓", m); };
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, timezoneId: "Asia/Karachi" });
// Record every print instead of opening the print dialog (also inside frames).
await ctx.addInitScript(() => {
  window.print = () => {
    const top = window.top;
    top.__prints = top.__prints || [];
    top.__prints.push(location.pathname + location.search);
  };
});
const page = await ctx.newPage();
let popups = 0; page.on("popup", () => popups++);
const errors = []; page.on("pageerror", (e) => errors.push(e.message));
const post = (path, body, method = "POST") => page.evaluate(async ([p, b, m]) => (await fetch(p, { method: m, headers: { "Content-Type": "application/json" }, body: JSON.stringify(b) })).json(), [path, body, method]);
const prints = () => page.evaluate(() => window.__prints || []);
await page.goto(B + "/setup");
await post("/api/setup", { name: "Admin", username: "admin", password: "admin-pass-123" });
await post("/api/auth/login", { username: "admin", password: "admin-pass-123" });
await post("/api/admin/tenants", { shopName: "UI Mart", shopType: "general", maxUsers: 3, ownerName: "Sana", username: "sana", password: "secret1" });
await post("/api/auth/logout", {});
await page.goto(B + "/login");
await page.fill('input[autocomplete="username"]', "sana");
await page.fill('input[type="password"]', "secret1");
await page.click('button[type="submit"]');
await page.waitForURL(B + "/");
await post("/api/products", { name: "Lux Soap", unit: "pcs", costPrice: 80, salePrice: 100, lowStockAlert: 1, openingStock: 100 });
await post("/api/parties", { type: "customer", name: "Bilal" });

await page.goto(B + "/settings");
await page.waitForSelector("text=Printing (this computer)");
const card = page.locator("div:has(> h2:has-text('Printing (this computer)'))");
await card.locator("label:has-text('Print the receipt automatically') input").check();
await card.locator("label:has-text('Shop copy for udhaar bills') input").check();
await card.locator("select[aria-label='Receipt paper']").selectOption("58");
const saved = await page.evaluate(() => JSON.parse(localStorage.getItem("dukaan:print") || "{}"));
ok(saved.auto === true && saved.udhaarCopy === true && saved.paper === "58", "printing settings saved on this computer");
await card.locator("button:has-text('Print a test receipt')").click();
await page.waitForFunction(() => (window.__prints || []).some((p) => p.startsWith("/receipt/test")), null, { timeout: 15000 });
ok(true, "test receipt printed through a hidden frame");
await page.screenshot({ path: `${out}/print-settings.png` });

await page.goto(B + "/pos");
await page.click("button:has-text('Lux Soap')");
await page.click("text=Take Payment");
await page.click("[role=dialog] button:has-text('Confirm & Save Bill')");
await page.waitForSelector("text=Receipt sent to the printer");
await page.waitForFunction(() => (window.__prints || []).some((p) => /^\/receipt\/[a-f0-9]{24}\?print=1$/.test(p)), null, { timeout: 15000 });
ok(true, "cash bill printed automatically (one copy)");
ok(popups === 0, "no pop-up window used");
await page.click("[role=dialog] button:has-text('Next bill')");
await page.click("button:has-text('Lux Soap')");
await page.click("text=Walk-in customer");
await page.click("[role=dialog] >> text=Bilal");
await page.click("text=Take Payment");
await page.click("[role=dialog] button:has-text('Udhaar')");
await page.click("[role=dialog] button:has-text('Confirm & Save Bill')");
await page.waitForSelector("text=Receipt sent to the printer");
await page.waitForFunction(() => (window.__prints || []).some((p) => p.includes("copies=2")), null, { timeout: 15000 });
ok(true, "udhaar bill printed with a shop copy");
const url = (await prints()).find((p) => p.includes("copies=2"));
const rp = await ctx.newPage();
await rp.goto(B + url.replace("print=1&", ""));
await rp.waitForSelector("text=SHOP COPY");
const style = await rp.evaluate(() => [...document.querySelectorAll("style")].map((s) => s.textContent).join(" "));
ok(style.includes("58mm"), "58 mm paper used on the receipt");
ok((await rp.locator("text=/^TOTAL$/").count()) === 2 && (await rp.locator("text=Customer signature").count()) === 1, "two copies; the shop copy has a signature line");
await rp.screenshot({ path: `${out}/print-two-copies.png`, fullPage: true });
await rp.close();
await page.click("[role=dialog] label:has-text('Print the receipt automatically') input");
ok(await page.evaluate(() => JSON.parse(localStorage.getItem("dukaan:print") || "{}").auto === false), "cashier can switch auto-print off from the bill window");
ok(errors.length === 0, "no page errors " + JSON.stringify(errors));
await browser.close();
