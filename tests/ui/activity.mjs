import { chromium } from "playwright";
import { B } from "../lib/harness.mjs";
const out = process.argv[2];
const ok = (c, m) => { if (!c) { console.log("  ✗", m); process.exitCode = 1; } else console.log("  ✓", m); };
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, timezoneId: "Asia/Karachi", acceptDownloads: true });
const page = await ctx.newPage();
const errors = []; page.on("pageerror", (e) => errors.push(e.message));
await page.goto(B + "/login");
await page.fill('input[autocomplete="username"]', "hamza");
await page.fill('input[type="password"]', "secret1");
await page.click('button[type="submit"]');
await page.waitForURL(B + "/");
await page.click("aside >> text=Activity Log");
await page.waitForSelector("text=Price changed on bill");
let t = await page.locator("tbody").innerText();
ok(t.includes("Payment cancelled") && t.includes("Wastage") && t.includes("Day closed"), "log lists the actions");
ok(await page.locator("tr.bg-rose-50\\/40").count() >= 3, "risky actions highlighted");
await page.screenshot({ path: `${out}/activity.png`, fullPage: false });
await page.selectOption("select[aria-label=Type]", "drawer");
await page.waitForTimeout(800);
t = await page.locator("tbody").innerText();
ok(t.includes("Drawer opened") && !t.includes("Payment cancelled"), "filter by type");
const [dl] = await Promise.all([page.waitForEvent("download"), page.click("button:has-text('Excel')")]);
ok(/activity-.*\.csv/.test(dl.suggestedFilename()), "Excel export " + dl.suggestedFilename());
await page.setViewportSize({ width: 390, height: 844 });
await page.reload();
await page.waitForTimeout(1200);
ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), "fits a phone");
ok(errors.length === 0, "no page errors " + JSON.stringify(errors));
await browser.close();
