import { chromium } from "playwright";
import { B } from "../lib/harness.mjs";
const out = process.argv[2];
const ok = (c, m) => { if (!c) { console.log("  ✗", m); process.exitCode = 1; } else console.log("  ✓", m); };
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, timezoneId: "Asia/Karachi" });
const page = await ctx.newPage();
const errors = []; page.on("pageerror", (e) => errors.push(e.message));
const post = (path, body) => page.evaluate(async ([p, b]) => (await fetch(p, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(b) })).json(), [path, body]);
await page.goto(B + "/setup");
await post("/api/setup", { name: "Admin", username: "admin", password: "admin-pass-123" });
await post("/api/auth/login", { username: "admin", password: "admin-pass-123" });
await post("/api/admin/tenants", { shopName: "UI Mart", shopType: "general", maxUsers: 3, ownerName: "Sana", username: "sana", password: "secret1" });
await post("/api/auth/logout", {});
await page.goto(B + "/login");
await page.fill('input[autocomplete="username"]', "sana");
await page.fill('input[type="password"]', "secret1");
await page.click('button[type="submit"]');
await page.waitForURL(B + "/");

// Product form: add packs and wholesale price
await page.goto(B + "/products");
await page.click("button:has-text('Add product')");
await page.fill('input[placeholder^="e.g. Sugar"]', "Lux Soap");
const form = page.locator("#product-form");
await form.locator("input[placeholder='0']").nth(0).fill("80");
await form.locator("input[placeholder='0']").nth(1).fill("100");
await form.locator("input[aria-label='Wholesale price']").fill("90");
await form.locator("button:has-text('Add pack')").click();
await form.locator("input[aria-label='Units in pack']").fill("24");
await form.locator("input[aria-label='Pack price']").fill("2300");
await form.locator("input[aria-label='Pack wholesale price']").fill("2100");
await form.locator("input[aria-label='Pack barcode']").fill("CARTON-LUX");
await page.screenshot({ path: `${out}/pack-form.png` });
await page.click("button:has-text('Add product')>> nth=-1");
await page.waitForSelector("text=Product added");
const prod = (await page.evaluate(async () => (await (await fetch("/api/products?q=Lux")).json())[0]));
ok(prod.packs?.[0]?.name === "Carton" && prod.packs[0].size === 24 && prod.wholesalePrice === 90, "product saved with carton and wholesale price");
await page.evaluate(async (id) => fetch(`/api/products/${id}/stock`, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ mode: "add", qty: 200 }) }), prod._id);
await post("/api/parties", { type: "customer", name: "Shah Traders", priceLevel: "wholesale" });

// POS
await page.goto(B + "/pos");
await page.waitForSelector("button:has-text('Lux Soap')");
await page.click("button:has-text('Lux Soap')");
const cartPanel = page.locator("aside:has-text('Bill items')");
await cartPanel.locator("select[aria-label='Sell Lux Soap as']").selectOption("Carton");
await page.waitForTimeout(200);
ok((await cartPanel.innerText()).includes("Rs 2,300 / Carton (24"), "line switched to carton at 2,300");
await page.keyboard.type("CARTON-LUX", { delay: 5 });
await page.keyboard.press("Enter");
await page.waitForTimeout(300);
ok((await cartPanel.locator("li input[type=number]").first().inputValue()) === "2", "scanning carton barcode adds another carton (qty 2)");
await page.click("button:has-text('Lux Soap')");
await page.waitForTimeout(200);
ok((await cartPanel.locator("li").count()) === 2, "piece is a separate line");
ok((await cartPanel.innerText()).includes("Rs 4,700"), "total 2 x 2300 + 100 = 4,700");
await page.click("text=Walk-in customer");
await page.waitForSelector("text=Shah Traders");
await page.click("[role=dialog] >> text=Shah Traders");
await page.waitForTimeout(400);
const t = await cartPanel.innerText();
ok(t.includes("Wholesale prices") && t.includes("Rs 4,290"), "wholesale customer: 2 x 2100 + 90 = 4,290");
await page.screenshot({ path: `${out}/pack-pos.png` });
await page.click("text=Take Payment");
await page.click("[role=dialog] button:has-text('Confirm & Save Bill')");
await page.waitForSelector("text=Bill saved");
const [rp] = await Promise.all([page.waitForEvent("popup"), page.click("[role=dialog] button:has-text('Print')")]);
await rp.waitForSelector("text=TOTAL");
const rt = await rp.innerText("body");
ok(rt.includes("2 Carton (24) × 2,100") && rt.includes("4,290"), "receipt shows cartons at wholesale price");
await rp.close();
ok(errors.length === 0, "no page errors " + JSON.stringify(errors));
await browser.close();
