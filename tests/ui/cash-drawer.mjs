import { chromium } from "playwright";
import { B, norm } from "../lib/harness.mjs";
const out = process.argv[2];
const ok = (c, m) => { if (!c) { console.log("  ✗", m); process.exitCode = 1; } else console.log("  ✓", m); };
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, timezoneId: "Asia/Karachi" });
const page = await ctx.newPage();
const errors = []; page.on("pageerror", (e) => errors.push(e.message));
let native = 0; page.on("dialog", (d) => { native++; d.dismiss(); });
const post = (path, body) => page.evaluate(async ([p, b]) => (await fetch(p, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(b) })).json(), [path, body]);
await page.goto(B + "/setup");
await post("/api/setup", { name: "Admin", username: "admin", password: "admin-pass-123" });
await post("/api/auth/login", { username: "admin", password: "admin-pass-123" });
await post("/api/admin/tenants", { shopName: "UI Mart", shopType: "general", maxUsers: 3, ownerName: "Sana", username: "sana", password: "secret1" });
await post("/api/auth/logout", {});
await page.goto(B + "/login");
await page.fill('input[autocomplete="username"]', "sana");
await page.fill('input[type="password"]', "secret1");
await page.click('button[type="submit"]');
await page.waitForURL(B + "/");
const p = await post("/api/products", { name: "Ghee 1kg", unit: "pcs", costPrice: 400, salePrice: 500, lowStockAlert: 1, openingStock: 50 });

await page.goto(B + "/pos");
await page.waitForSelector("text=Drawer not open");
ok(true, "POS reminds that the drawer is not open");
await page.click("text=Drawer not open");
await page.waitForURL(/\/drawer/);
await page.waitForSelector("text=Start the day");
await page.fill("input[aria-label='Opening cash']", "2000");
await page.click("button:has-text('Open drawer')");
await page.waitForSelector("text=Drawer open");
ok(true, "drawer opened");
await post("/api/sales", { items: [{ productId: p._id, qty: 1 }], paymentMethod: "cash" });
await page.reload();
await page.waitForSelector("text=Cash that should be in the drawer");
ok((await page.locator("body").innerText().then(norm)).includes("Rs 2,500"), "expected cash 2,500 after a Rs 500 cash sale");
await page.click("button:has-text('Cash out')");
await page.fill("[role=dialog] input[aria-label=Amount]", "300");
await page.click("[role=dialog] button:has-text('Bank deposit')");
await page.click("[role=dialog] button:has-text('Save')");
await page.waitForSelector("text=Cash out recorded");
await page.waitForTimeout(500);
ok((await page.locator("body").innerText().then(norm)).includes("Rs 2,200"), "expected 2,200 after Rs 300 cash out");
await page.screenshot({ path: `${out}/drawer-open.png`, fullPage: true });
await page.click("button:has-text('Close day')");
await page.waitForSelector("text=Close day — count the cash");
await page.fill("input[aria-label='Rs 1000 notes']", "2");
await page.fill("input[aria-label='Rs 100 notes']", "1");
await page.fill("input[aria-label='Coins total']", "100");
ok((await page.locator("[role=dialog]").innerText().then(norm)).includes("Rs 2,200"), "count adds up to 2,200");
await page.screenshot({ path: `${out}/drawer-close.png` });
await page.click("[role=dialog] button:has-text('Close day')");
await page.waitForSelector("[role=alertdialog]");
await page.click("[role=alertdialog] button:has-text('Close day')");
await page.waitForSelector("text=Day closed");
ok((await page.locator("[role=dialog]").innerText().then(norm)).includes("Exact"), "result: exact");
const [z] = await Promise.all([page.waitForEvent("popup"), page.click("[role=dialog] button:has-text('Z report')")]);
await z.waitForSelector("text=Z REPORT");
const zt = await z.innerText("body").then(norm);
ok(zt.includes("CASH MATCHES") && zt.includes("Bank deposit") && zt.includes("1,000 × 2"), "Z report: matches, cash out, note count");
await z.screenshot({ path: `${out}/z-report.png`, fullPage: true });
await z.close();
await page.click("[role=dialog] button:has-text('Done')");
await page.waitForSelector("text=Start the day");
ok((await page.locator("tbody").innerText().then(norm)).includes("SFT-000001"), "history shows the closed day");
await page.setViewportSize({ width: 390, height: 844 });
await page.goto(B + "/drawer");
await page.waitForSelector("text=Start the day");
ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), "drawer page fits a phone");
ok(native === 0, "no browser pop-ups");
ok(errors.length === 0, "no page errors " + JSON.stringify(errors));
await browser.close();
