section("Price history");
let h = await owner.call(`/api/products/${sugar._id}/price-history`);
ok(h.rows.some((r) => r.source === "added" && r.field === "salePrice" && r.to === 120), "first price recorded when the item was added");
await owner.call(`/api/products/${sugar._id}`, { method: "PUT", body: { name: "Sugar", unit: "kg", costPrice: 100, salePrice: 130, wholesalePrice: 112, lowStockAlert: 5, category: grocery._id } });
h = await owner.call(`/api/products/${sugar._id}/price-history`);
const edit = h.rows.find((r) => r.source === "edit");
ok(edit && edit.field === "salePrice" && edit.from === 120 && edit.to === 130 && edit.userName === "Zubair", "edit recorded: 120 → 130 by Zubair");
eq(h.rows.filter((r) => r.source === "edit").length, 1, "unchanged prices are not recorded");
await owner.call("/api/purchases", { body: { items: [{ productId: sugar._id, qty: 10, cost: 105, salePrice: 135 }] } });
h = await owner.call(`/api/products/${sugar._id}/price-history`);
const bought = h.rows.filter((r) => r.source === "purchase");
ok(bought.some((r) => r.field === "costPrice" && r.from === 100 && r.to === 105), "purchase recorded the new cost price");
ok(bought.some((r) => r.field === "salePrice" && r.from === 130 && r.to === 135), "purchase recorded the new sale price");
ok(bought.every((r) => r.refNo && r.refNo.length > 2), "purchase number kept: " + bought[0]?.refNo);
eq(h.rows[0].source, "purchase", "newest first");
const ch = await cashier.call(`/api/products/${sugar._id}/price-history`);
ok(ch.rows.every((r) => r.field !== "costPrice") && ch.product.costPrice === undefined, "cashier sees no cost prices");
await other.call(`/api/products/${sugar._id}/price-history`, { expect: 404 });
ok(true, "another shop cannot see it");

section("Bulk price update");
await cashier.call("/api/products/bulk-price", { body: { scope: "all", field: "salePrice", mode: "percent", value: 5, preview: true }, expect: 403 });
ok(true, "cashier cannot change prices in bulk");
await owner.call("/api/products/bulk-price", { body: { scope: "all", field: "salePrice", mode: "percent", value: 0, preview: true }, expect: 400 });
await owner.call("/api/products/bulk-price", { body: { scope: "all", field: "salePrice", mode: "percent", value: -100 }, expect: 400 });
await owner.call("/api/products/bulk-price", { body: { scope: "category", field: "salePrice", mode: "percent", value: 5 }, expect: 400 });
ok(true, "0%, −100% and a missing category are refused");
let pv = await owner.call("/api/products/bulk-price", { body: { scope: "category", categoryId: grocery._id, field: "salePrice", mode: "percent", value: 10, round: 5, preview: true } });
eq(pv.scope, "Kiryana Test", "preview names the category");
eq(pv.total, 2, "2 grocery items");
const pvSugar = pv.rows.find((r) => r.name === "Sugar");
eq(pvSugar.from, 135, "sugar now 135");
eq(pvSugar.to, 150, "135 + 10% = 148.5 → rounded to 150");
eq(pv.rows.find((r) => r.name === "Cooking Oil").to, 495, "oil 450 + 10% = 495");
eq((await owner.call(`/api/products/${sugar._id}`)).product.salePrice, 135, "preview saves nothing");
const r = await manager.call("/api/products/bulk-price", { body: { scope: "category", categoryId: grocery._id, field: "salePrice", mode: "percent", value: 10, round: 5 } });
eq(r.changed, 2, "manager changed 2 prices");
let p = (await owner.call(`/api/products/${oil._id}`)).product;
eq(p.salePrice, 495, "oil 495");
eq(p.packs[0].price, 5720, "carton price moved too: 5200 + 10% = 5720");
eq((await owner.call(`/api/products/${cola._id}`)).product.salePrice, 100, "drinks untouched");
h = await owner.call(`/api/products/${oil._id}/price-history`);
ok(h.rows[0].source === "bulk" && h.rows[0].from === 450 && h.rows[0].to === 495 && h.rows[0].userName === "Naveed", "bulk change in the price history");
pv = await owner.call("/api/products/bulk-price", { body: { scope: "all", field: "salePrice", mode: "amount", value: -20, preview: true } });
eq(pv.rows.find((r) => r.name === "Cola").to, 80, "amount: 100 − 20 = 80");
pv = await owner.call("/api/products/bulk-price", { body: { scope: "ids", productIds: [cola._id], field: "salePrice", mode: "amount", value: -30, preview: true } });
eq(pv.belowCost, 1, "below-cost warning (70 < cost 80)");
pv = await owner.call("/api/products/bulk-price", { body: { scope: "ids", productIds: [cola._id], field: "salePrice", mode: "amount", value: -100, preview: true } });
eq(pv.skipped, 1, "a price that would be 0 is skipped");
eq(pv.changing, 0, "nothing would change");
await owner.call("/api/products/bulk-price", { body: { scope: "ids", productIds: [cola._id], field: "salePrice", mode: "amount", value: -100 }, expect: 400 });
ok(true, "applying a change that changes nothing is refused");
await owner.call("/api/products/bulk-price", { body: { scope: "all", field: "salePrice", mode: "amount", value: 2 } });
p = (await owner.call(`/api/products/${oil._id}`)).product;
eq(p.salePrice, 497, "amount per loose unit: 495 + 2");
eq(p.packs[0].price, 5720 + 24, "carton: + 2 × 12");
pv = await owner.call("/api/products/bulk-price", { body: { scope: "all", field: "wholesalePrice", mode: "percent", value: 5, preview: true } });
ok(pv.total === 1 && pv.rows[0].name === "Sugar", "wholesale: only items that have a wholesale price");
pv = await other.call("/api/products/bulk-price", { body: { scope: "ids", productIds: [cola._id], field: "salePrice", mode: "percent", value: 5, preview: true } });
eq(pv.total, 0, "another shop's items are never touched");

section("Correct a saved bill");
const before = (await owner.call(`/api/products/${cola._id}`)).product.stock;
const bill = await owner.call("/api/sales", { body: { items: [{ productId: cola._id, qty: 4, discount: 10 }, { productId: oil._id, qty: 1, pack: "Carton" }], paymentMethod: "credit", customerId: ali._id, discount: 15 } });
const aliAfterBill = (await owner.call(`/api/parties/${ali._id}`)).party.balance;
await cashier.call(`/api/sales/${bill._id}/correct`, { body: {}, expect: 403 });
ok(true, "cashier cannot correct a bill");
const c = await manager.call(`/api/sales/${bill._id}/correct`, { body: {} });
ok(typeof c.returnNo === "string" && c.returnNo.length > 2, "bill returned in full: " + c.returnNo);
eq(c.sale.invoiceNo, bill.invoiceNo, "old bill number given back");
eq(c.lines.length, 2, "both lines come back");
const colaLine = c.lines.find((l) => l.productId === cola._id);
ok(colaLine.qty === 4 && colaLine.price === 102 && colaLine.discount === 10, "cola ×4 at 102 with its Rs 10 discount");
const oilLine = c.lines.find((l) => l.productId === oil._id);
ok(oilLine.pack === "Carton" && oilLine.qty === 1 && oilLine.price === 430 * 12, "oil comes back as 1 carton at its bill price");
eq(c.discount, 15, "bill discount comes back");
eq(c.customer?._id, ali._id, "customer comes back");
const old = (await owner.call(`/api/sales?q=${bill.invoiceNo}&from=2000-01-01&to=2100-01-01`)).find((x) => x._id === bill._id);
eq(old.status, "returned", "old bill is returned");
eq((await owner.call(`/api/products/${cola._id}`)).product.stock, before, "stock back");
await manager.call(`/api/sales/${bill._id}/correct`, { body: {}, expect: 400 }).then((e) => ok(/already/.test(e.error), "cannot correct the same bill twice"));
await cashier.call("/api/sales", { body: { items: [{ productId: cola._id, qty: 3 }], paymentMethod: "cash", correctionOf: bill._id }, expect: 403 });
ok(true, "cashier cannot save a correction");
const fixed = await manager.call("/api/sales", { body: { items: [{ productId: cola._id, qty: 3, discount: 10 }, { productId: oil._id, qty: 1, pack: "Carton", price: 430 * 12 }], paymentMethod: "credit", customerId: ali._id, discount: 15, correctionOf: bill._id } });
eq(fixed.correctionOf?.invoiceNo, bill.invoiceNo, "new bill links to the old one");
eq(fixed.total, 306 - 10 + 5160 - 15, "corrected total");
const list = await owner.call(`/api/sales?from=2000-01-01&to=2100-01-01`);
eq(list.find((x) => x._id === bill._id).correctedBy?.invoiceNo, fixed.invoiceNo, "old bill shows the bill that corrected it");
await manager.call("/api/sales", { body: { items: [{ productId: cola._id, qty: 1 }], paymentMethod: "cash", correctionOf: bill._id }, expect: 400 }).then((e) => ok(/already corrected/.test(e.error), "a bill is corrected only once"));
const live = await owner.call("/api/sales", { body: { items: [{ productId: cola._id, qty: 1 }], paymentMethod: "cash" } });
await owner.call("/api/sales", { body: { items: [{ productId: cola._id, qty: 1 }], paymentMethod: "cash", correctionOf: live._id }, expect: 400 }).then((e) => ok(/not returned/.test(e.error), "only a returned bill can be corrected"));
const bal = (await owner.call(`/api/parties/${ali._id}`)).party.balance;
eq(r2(bal - aliAfterBill), r2(fixed.total - bill.total), "khata: old udhaar taken off, new udhaar added");
const acts = (await owner.call("/api/activity")).rows;
ok(acts.some((x) => x.action === "sale.correct" && x.summary.startsWith(`${bill.invoiceNo} corrected: new bill ${fixed.invoiceNo}`)), "correction is in the activity log");

// Bills partly returned before: only what is left comes back.
const b2 = await owner.call("/api/sales", { body: { items: [{ productId: cola._id, qty: 5 }], paymentMethod: "cash" } });
await owner.call(`/api/sales/${b2._id}/return`, { body: { items: [{ index: 0, qty: 2 }] } });
const c2 = await owner.call(`/api/sales/${b2._id}/correct`, { body: {} });
eq(c2.lines[0].qty, 3, "partly returned bill: the 3 left come back");
await other.call(`/api/sales/${b2._id}/correct`, { body: {}, expect: 404 });
ok(true, "another shop cannot correct it");

await done();
