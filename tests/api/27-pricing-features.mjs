import { Client, ok, eq, section, r2, done } from "../lib/harness.mjs";

// ---------- Special prices, item discount, price history, bulk price update, correcting a bill ----------
const admin = new Client("admin"), owner = new Client("owner"), manager = new Client("manager"), cashier = new Client("cashier");
await admin.call("/api/setup", { body: { name: "Admin", username: "admin", password: "admin-pass-123" } });
await admin.call("/api/admin/tenants", { body: { shopName: "Price Mart", shopType: "general", maxUsers: 5, ownerName: "Zubair", username: "zubair", password: "secret1" } });
await owner.login("zubair", "secret1");
await owner.call("/api/users", { body: { name: "Naveed", username: "naveed", password: "secret2", role: "manager" } });
await owner.call("/api/users", { body: { name: "Kashif", username: "kashif", password: "secret3", role: "cashier" } });
await manager.login("naveed", "secret2");
await cashier.login("kashif", "secret3");

const grocery = await owner.call("/api/categories", { body: { name: "Kiryana Test" } });
const drinks = await owner.call("/api/categories", { body: { name: "Drinks Test" } });
const sugar = await owner.call("/api/products", { body: { name: "Sugar", unit: "kg", costPrice: 100, salePrice: 120, wholesalePrice: 112, lowStockAlert: 5, openingStock: 200, category: grocery._id } });
const oil = await owner.call("/api/products", {
  body: { name: "Cooking Oil", unit: "litre", costPrice: 400, salePrice: 450, lowStockAlert: 5, openingStock: 120, category: grocery._id, packs: [{ name: "Carton", size: 12, price: 5200 }] },
});
const cola = await owner.call("/api/products", { body: { name: "Cola", unit: "pcs", costPrice: 80, salePrice: 100, lowStockAlert: 5, openingStock: 100, category: drinks._id } });
const phone = await owner.call("/api/products", { body: { name: "Phone X", unit: "pcs", costPrice: 20000, salePrice: 25000, lowStockAlert: 1, trackSerial: true } });
eq(String(sugar.category), grocery._id, "products made in their category");

section("Special prices per customer");
const ali = await owner.call("/api/parties", { body: { type: "customer", name: "Ali Bhai", phone: "03001234567" } });
const shah = await owner.call("/api/parties", { body: { type: "customer", name: "Shah Traders", priceLevel: "wholesale" } });
eq((await owner.call(`/api/parties/${ali._id}/prices`)).length, 0, "no special prices at first");
await cashier.call(`/api/parties/${ali._id}/prices`, { method: "PUT", body: { prices: [{ productId: sugar._id, price: 100 }] }, expect: 403 });
ok(true, "cashier cannot set special prices");
await owner.call(`/api/parties/${ali._id}/prices`, { method: "PUT", body: { prices: [{ productId: sugar._id, price: 0 }] }, expect: 400 }).then((e) => ok(/more than zero/.test(e.error), "price 0 refused: " + e.error));
await owner.call(`/api/parties/${ali._id}/prices`, { method: "PUT", body: { prices: [{ productId: sugar._id, price: 100 }, { productId: sugar._id, price: 99 }] }, expect: 400 }).then((e) => ok(/twice/.test(e.error), "same item twice refused"));
await owner.call(`/api/parties/${ali._id}/prices`, { method: "PUT", body: { prices: [{ productId: phone._id, price: 100 }] }, expect: 400 }).then((e) => ok(/IMEI/.test(e.error), "phone (IMEI) cannot have a special price"));
await owner.call(`/api/parties/${ali._id}/prices`, { method: "PUT", body: { prices: [{ productId: "0123456789abcdef01234567", price: 100 }] }, expect: 400 }).then((e) => ok(/not found/.test(e.error), "unknown item refused"));
await manager.call(`/api/parties/${ali._id}/prices`, { method: "PUT", body: { prices: [{ productId: sugar._id, price: 100 }, { productId: oil._id, price: 420 }] } });
let sp = await cashier.call(`/api/parties/${ali._id}/prices`);
eq(sp.length, 2, "manager saved 2 special prices; cashier can see them");
eq(sp.find((x) => x.productId === sugar._id).price, 100, "sugar 100 for Ali");
eq(sp.find((x) => x.productId === sugar._id).salePrice, 120, "normal price shown beside it");

let s = await cashier.call("/api/sales", { body: { items: [{ productId: sugar._id, qty: 5, price: 1 }, { productId: cola._id, qty: 2 }], paymentMethod: "cash", customerId: ali._id } });
eq(s.items[0].price, 100, "cashier bill for Ali: sugar at the special 100 (typed price ignored)");
ok(s.items[0].special === true, "line marked special");
eq(s.items[1].price, 100, "cola (no special price) at normal 100");
eq(s.total, 500 + 200, "total 700");
s = await cashier.call("/api/sales", { body: { items: [{ productId: oil._id, qty: 1, pack: "Carton" }], paymentMethod: "cash", customerId: ali._id } });
eq(s.total, 420 * 12, "carton for Ali = special 420 × 12");
s = await cashier.call("/api/sales", { body: { items: [{ productId: sugar._id, qty: 5 }], paymentMethod: "cash" } });
eq(s.total, 600, "walk-in pays the normal 120");
s = await owner.call("/api/sales", { body: { items: [{ productId: sugar._id, qty: 1, price: 95 }], paymentMethod: "cash", customerId: ali._id } });
eq(s.total, 95, "owner can still type another price for Ali");
await owner.call(`/api/parties/${shah._id}/prices`, { method: "PUT", body: { prices: [{ productId: sugar._id, price: 105 }] } });
s = await cashier.call("/api/sales", { body: { items: [{ productId: sugar._id, qty: 1 }, { productId: oil._id, qty: 1 }], paymentMethod: "cash", customerId: shah._id } });
eq(s.items[0].price, 105, "wholesale customer: special price beats wholesale price");
eq(s.items[1].price, 450, "no wholesale price for oil → normal");

// Offers do not stack on a special price.
await owner.call("/api/promotions", { body: { name: "Sugar 10% off", kind: "percent", value: 10, appliesTo: "products", products: [sugar._id] } });
s = await cashier.call("/api/sales", { body: { items: [{ productId: sugar._id, qty: 2 }], paymentMethod: "cash", customerId: ali._id } });
eq(s.total, 200, "no offer on top of a special price");
const act = await owner.call("/api/activity?q=Special");
ok(act.rows.some((x) => x.action === "party.prices" && x.summary.includes("Special prices for Ali Bhai: Sugar Rs 100")), "special prices change is in the activity log");
await owner.call(`/api/parties/${ali._id}/prices`, { method: "PUT", body: { prices: [{ productId: oil._id, price: 430 }] } });
sp = await owner.call(`/api/parties/${ali._id}/prices`);
ok(sp.length === 1 && sp[0].price === 430, "sugar removed, oil changed to 430");
s = await cashier.call("/api/sales", { body: { items: [{ productId: sugar._id, qty: 1 }], paymentMethod: "cash", customerId: ali._id } });
eq(s.total, 108, "after removing the special price Ali pays the normal price with the offer (120 − 10%)");
const other = new Client("other");
await admin.call("/api/admin/tenants", { body: { shopName: "Other Shop", shopType: "general", maxUsers: 2, ownerName: "Other", username: "othr", password: "secret9" } });
await other.login("othr", "secret9");
await other.call(`/api/parties/${ali._id}/prices`, { expect: 404 });
await other.call(`/api/parties/${ali._id}/prices`, { method: "PUT", body: { prices: [] }, expect: 404 });
ok(true, "another shop cannot read or change them");

