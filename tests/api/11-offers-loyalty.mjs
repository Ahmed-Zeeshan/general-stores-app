import { Client, ok, eq, section, day, done } from "../lib/harness.mjs";

// ---------- Offers and loyalty points ----------
const admin = new Client("admin"), owner = new Client("owner"), cashier = new Client("cashier");
await admin.call("/api/setup", { body: { name: "Admin", username: "admin", password: "admin-pass-123" } });
await admin.call("/api/admin/tenants", { body: { shopName: "Offer Mart", shopType: "general", maxUsers: 4, ownerName: "Hamza", username: "hamza", password: "secret1" } });
await owner.login("hamza", "secret1");
await owner.call("/api/users", { body: { name: "Kashif", username: "kashif", password: "secret2", role: "cashier" } });
await cashier.login("kashif", "secret2");
const cats = await owner.call("/api/categories");
const snacks = cats[0];
const biscuit = await owner.call("/api/products", { body: { name: "Biscuit", unit: "pcs", costPrice: 40, salePrice: 50, lowStockAlert: 1, openingStock: 500, category: snacks._id } });
const soap = await owner.call("/api/products", { body: { name: "Soap", unit: "pcs", costPrice: 80, salePrice: 100, lowStockAlert: 1, openingStock: 500 } });
const tea = await owner.call("/api/products", { body: { name: "Tea", unit: "pcs", costPrice: 900, salePrice: 1000, lowStockAlert: 1, openingStock: 500 } });
const sell = (who, items, extra = {}, expect = 200) => who.call("/api/sales", { body: { items, paymentMethod: "cash", ...extra }, expect });

section("Offers");
await cashier.call("/api/promotions", { body: { name: "x", kind: "percent", value: 10 }, expect: 403 }).then(() => ok(true, "cashier cannot create offers"));
await owner.call("/api/promotions", { body: { name: "Bad", kind: "percent", value: 0 }, expect: 400 }).then(() => ok(true, "0% refused"));
await owner.call("/api/promotions", { body: { name: "Bad", kind: "bxgy" }, expect: 400 }).then(() => ok(true, "buy/get numbers required"));
await owner.call("/api/promotions", { body: { name: "Bad", kind: "amount", value: 5, appliesTo: "products" }, expect: 400 }).then(() => ok(true, "chosen items required"));
const pSnacks = await owner.call("/api/promotions", { body: { name: "Snacks 10%", kind: "percent", value: 10, appliesTo: "categories", categories: [snacks._id] } });
await owner.call("/api/promotions", { body: { name: "Tea Rs 20 off", kind: "amount", value: 20, appliesTo: "products", products: [tea._id] } });
await owner.call("/api/promotions", { body: { name: "Soap 2+1", kind: "bxgy", buyQty: 2, freeQty: 1, appliesTo: "products", products: [soap._id] } });
await owner.call("/api/promotions", { body: { name: "Big bill 5%", kind: "bill", value: 5, minAmount: 2000, maxDiscount: 150 } });
eq((await cashier.call("/api/promotions")).length, 4, "cashier can read offers (for the counter)");
let s = await sell(cashier, [{ productId: biscuit._id, qty: 4 }, { productId: soap._id, qty: 3 }, { productId: tea._id, qty: 1 }]);
eq(s.items[0].promo.amount, 20, "biscuits 10% off (Rs 20)");
eq(s.items[1].promo.amount, 100, "3 soaps: 1 free");
eq(s.items[2].promo.amount, 20, "tea Rs 20 off");
eq(s.total, 1360, "total 1,360 (no bill offer under 2,000)");
eq(s.promoTotal, 140, "offers on bill 140");
ok(!s.promo, "no bill offer");
s = await sell(cashier, [{ productId: tea._id, qty: 2 }, { productId: biscuit._id, qty: 2 }]);
eq(s.promo.amount, 102.5, "bill offer 5% of 2,050");
eq(s.total, 2050 - 102.5, "total after bill offer");
s = await sell(cashier, [{ productId: tea._id, qty: 4 }]);
eq(s.promo.amount, 150, "bill offer capped at Rs 150");
const p15 = await owner.call("/api/promotions", { body: { name: "Everything 15%", kind: "percent", value: 15 } });
s = await sell(cashier, [{ productId: biscuit._id, qty: 2 }, { productId: tea._id, qty: 1 }]);
ok(s.items[0].promo.name === "Everything 15%" && s.items[1].promo.amount === 150, "best offer per item wins (15% beats 10% and Rs 20)");
await owner.call(`/api/promotions/${p15._id}`, { method: "DELETE" });
await owner.call("/api/promotions", { body: { name: "Old", kind: "percent", value: 50, endsAt: day(-1) } });
await owner.call("/api/promotions", { body: { name: "Future", kind: "percent", value: 50, startsAt: day(2) } });
await owner.call("/api/promotions", { body: { name: "Off", kind: "percent", value: 50, active: false } });
s = await sell(cashier, [{ productId: soap._id, qty: 1 }]);
ok(!s.items[0].promo && s.total === 100, "ended, future and switched-off offers not applied");
const today = await owner.call("/api/promotions", { body: { name: "Ends today", kind: "amount", value: 5, appliesTo: "products", products: [soap._id], endsAt: day(0) } });
s = await sell(cashier, [{ productId: soap._id, qty: 1 }]);
eq(s.items[0].promo?.name, "Ends today", "offer ending today still runs today");
await owner.call(`/api/promotions/${today._id}`, { method: "DELETE" });
const shah = await owner.call("/api/parties", { body: { type: "customer", name: "Shah Traders", priceLevel: "wholesale" } });
s = await sell(cashier, [{ productId: soap._id, qty: 3 }], { customerId: shah._id });
ok(!s.items[0].promo && s.total === 300, "wholesale customers get no offers");
s = await sell(owner, [{ productId: biscuit._id, qty: 4, price: 45 }]);
ok(!s.items[0].promo && s.total === 180, "price typed by hand gets no offer");
const soapBill = await sell(cashier, [{ productId: soap._id, qty: 3 }]);
const r = await owner.call(`/api/sales/${soapBill._id}/return`, { body: { items: [{ index: 0, qty: 1 }] } });
eq(r.return.total, 66.67, "returning 1 of 3 (2+1 offer) refunds a third of 200");

section("Loyalty points");
await owner.call("/api/settings", { method: "PUT", body: { shopName: "Offer Mart", shopType: "general", taxEnabled: false, taxRate: 0, pricesIncludeTax: true, loyaltyEnabled: true, loyaltyEarnPer: 100, loyaltyPointValue: 1, loyaltyMinRedeem: 50 } });
await owner.call(`/api/promotions/${pSnacks._id}`, { method: "PUT", body: { name: "Snacks 10%", kind: "percent", value: 10, appliesTo: "categories", categories: [snacks._id], active: false } });
const bilal = await owner.call("/api/parties", { body: { type: "customer", name: "Bilal" } });
const pts = async () => (await owner.call(`/api/parties/${bilal._id}`)).party.points;
s = await sell(cashier, [{ productId: soap._id, qty: 13 }], { customerId: bilal._id });
eq(s.pointsEarned, Math.floor(s.total / 100), "points earned = Rs paid / 100");
let before = await pts();
eq(before, s.pointsEarned, "customer points");
s = await cashier.call("/api/sales", { body: { items: [{ productId: tea._id, qty: 1 }], paymentMethod: "cash", amountPaid: 500, customerId: bilal._id } });
eq(s.pointsEarned, 5, "udhaar part earns nothing (500 paid → 5)");
await sell(cashier, [{ productId: soap._id, qty: 1 }], { customerId: bilal._id, redeemPoints: 10 }, 400).then((e) => ok(/At least 50/.test(e.error), "below minimum refused"));
await sell(cashier, [{ productId: tea._id, qty: 5 }], { customerId: bilal._id });
before = await pts();
ok(before >= 50, `enough points now (${before})`);
s = await sell(cashier, [{ productId: tea._id, qty: 1 }], { customerId: bilal._id, redeemPoints: 60 });
eq(s.pointsRedeemed, 60, "60 points spent");
eq(s.pointsValue, 60, "worth Rs 60");
eq(s.total, 1000 - 20 - 60, "bill reduced by points (after the tea offer)");
eq(await pts(), before - 60 + s.pointsEarned, "balance after spend + earn");
await sell(cashier, [{ productId: tea._id, qty: 1 }], { customerId: bilal._id, redeemPoints: 100000 }, 400).then((e) => ok(/does not have/.test(e.error), "cannot spend more than the balance"));
await sell(cashier, [{ productId: tea._id, qty: 1 }], { redeemPoints: 60 }, 400).then(() => ok(true, "walk-in cannot spend points"));
await owner.call("/api/settings", { method: "PUT", body: { shopName: "Offer Mart", shopType: "general", taxEnabled: false, taxRate: 0, pricesIncludeTax: true, loyaltyMinRedeem: 1, loyaltyEnabled: true, loyaltyEarnPer: 100, loyaltyPointValue: 1 } });
const bal = await pts();
const race = await Promise.all([1, 2, 3].map(() => cashier.raw("/api/sales", { body: { items: [{ productId: tea._id, qty: 1 }], paymentMethod: "cash", customerId: bilal._id, redeemPoints: bal } }).then((x) => x.status)));
eq(race.filter((x) => x === 200).length, 1, `points spent only once when 3 bills use them together (${race.join(",")})`);
ok((await pts()) >= 0, "balance never negative from spending");
const earnBill = await sell(cashier, [{ productId: tea._id, qty: 3 }], { customerId: bilal._id });
const beforeRet = await pts();
await owner.call(`/api/sales/${earnBill._id}/return`, { body: { items: [{ index: 0, qty: 1 }] } });
const third = Math.round(earnBill.pointsEarned / 3);
eq(await pts(), beforeRet - third, "returning a third takes back a third of the points");
await owner.call(`/api/sales/${earnBill._id}/return`, { body: {} });
eq(await pts(), beforeRet - earnBill.pointsEarned, "full return takes back all points of that bill");
const hist = (await owner.call(`/api/parties/${bilal._id}`)).points;
ok(hist.some((h) => h.kind === "earn") && hist.some((h) => h.kind === "redeem") && hist.some((h) => h.kind === "return"), "points history: earn, spend, return");
await owner.call("/api/settings", { method: "PUT", body: { shopName: "Offer Mart", shopType: "general", taxEnabled: false, taxRate: 0, pricesIncludeTax: true, loyaltyEnabled: false } });
s = await sell(cashier, [{ productId: tea._id, qty: 1 }], { customerId: bilal._id });
ok(!s.pointsEarned, "no points when loyalty is off");
await sell(cashier, [{ productId: tea._id, qty: 1 }], { customerId: bilal._id, redeemPoints: 1 }, 400).then(() => ok(true, "cannot spend when loyalty is off"));
const backup = await owner.call("/api/backup");
ok(backup.data.promotions.length >= 6 && backup.data.pointsHistory.length > 3, "offers and points history in backup");
eq((await owner.raw("/promotions")).status, 200, "offers page");
eq((await owner.raw(`/receipt/${earnBill._id}`)).status, 200, "receipt page");

await done();
