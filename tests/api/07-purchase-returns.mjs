import { Client, ok, eq, section, r2, db, oid, done } from "../lib/harness.mjs";

// ---------- Purchase returns & cancel purchase ----------
const admin = new Client("admin"), owner = new Client("owner"), cashier = new Client("cashier"), other = new Client("other");
await admin.call("/api/setup", { body: { name: "Admin", username: "admin", password: "admin-pass-123" } });
await admin.call("/api/admin/tenants", { body: { shopName: "Stock Mart", shopType: "general", maxUsers: 4, ownerName: "Hamza", username: "hamza", password: "secret1" } });
await admin.call("/api/admin/tenants", { body: { shopName: "Other Shop", shopType: "general", maxUsers: 2, ownerName: "Zara", username: "zara", password: "secret1" } });
await owner.login("hamza", "secret1");
await other.login("zara", "secret1");
await owner.call("/api/users", { body: { name: "Kashif", username: "kashif", password: "secret2", role: "cashier" } });
await cashier.login("kashif", "secret2");
const rice = await owner.call("/api/products", { body: { name: "Rice", unit: "kg", costPrice: 200, salePrice: 250, lowStockAlert: 1 } });
const oil = await owner.call("/api/products", { body: { name: "Oil", unit: "pcs", costPrice: 500, salePrice: 600, lowStockAlert: 1 } });
const soap = await owner.call("/api/products", { body: { name: "Soap", unit: "pcs", costPrice: 100, salePrice: 120, lowStockAlert: 1 } });
const sup = await owner.call("/api/parties", { body: { type: "supplier", name: "Distributor" } });
const stock = async (p) => (await owner.call(`/api/products/${p._id}`)).product.stock;
const bal = async () => (await owner.call(`/api/parties/${sup._id}`)).party.balance;
const buy = (body) => owner.call("/api/purchases", { body });
const ret = (p, body, expect = 200, who = owner) => who.call(`/api/purchases/${p._id}/return`, { body, expect });
await owner.call("/api/shifts", { body: { openingCash: 1000 } });

section("Return part of a purchase");
const p1 = await buy({ supplierId: sup._id, amountPaid: 1000, items: [{ productId: rice._id, qty: 10, cost: 200 }, { productId: oil._id, qty: 5, cost: 500 }] });
eq(p1.status, "received", "new purchase status received");
eq(await bal(), 3500, "supplier payable 3500");
let r = await ret(p1, { items: [{ index: 0, qty: 2 }], reason: "Damaged" });
ok(/^PRN-000001$/.test(r.returnNo), "return number " + r.returnNo);
eq(r.total, 400, "2 kg at cost = 400");
eq(r.settlement, "khata", "default: taken off khata");
eq(await bal(), 3100, "payable reduced to 3100");
eq(await stock(rice), 8, "rice stock 8");
let p = await owner.call(`/api/purchases/${p1._id}`);
eq(p.status, "partially_returned", "purchase part returned");
eq(p.items[0].returnedQty, 2, "returned qty tracked");
eq(p.returns.length, 1, "purchase lists its return");
await ret(p1, { items: [{ index: 0, qty: 9 }] }, 400).then((e) => ok(/Only 8/.test(e.error), "over-return blocked: " + e.error));
await ret(p1, { items: [{ index: 0, qty: 1 }] }, 403, cashier).then(() => ok(true, "cashier cannot return to supplier"));
await other.call(`/api/purchases/${p1._id}/return`, { body: {}, expect: 404 }).then(() => ok(true, "other shop cannot touch this purchase"));
await owner.call("/api/sales", { body: { items: [{ productId: rice._id, qty: 7 }], paymentMethod: "cash" } });
await ret(p1, { items: [{ index: 0, qty: 2 }] }, 400).then((e) => ok(/Only 1 kg of Rice is in stock/.test(e.error), "cannot return stock already sold: " + e.error));
r = await ret(p1, { items: [{ index: 0, qty: 1 }], settlement: "cash" });
eq(r.settlement, "cash", "cash back from supplier");
eq(await bal(), 3100, "cash back does not change the khata");
eq(await stock(rice), 0, "rice stock 0");
const parallel = await Promise.all([1, 2, 3, 4, 5, 6].map(() => owner.raw(`/api/purchases/${p1._id}/return`, { body: { items: [{ index: 1, qty: 1 }] } }).then((x) => x.status)));
eq(parallel.filter((s) => s === 200).length, 5, `exactly 5 of 6 parallel oil returns accepted (${parallel.join(",")})`);
eq(await stock(oil), 0, "oil stock 0");
p = await owner.call(`/api/purchases/${p1._id}`);
eq(p.returnedTotal, 400 + 200 + 2500, "returned total 3100");
eq(p.status, "partially_returned", "still part returned (7 kg rice were sold)");
eq(await bal(), 3100 - 2500, "payable 600 after oil returned to khata");
await owner.call(`/api/purchases/${p1._id}/void`, { body: {}, expect: 400 }).then((e) => ok(/already returned/.test(e.error), "cannot cancel after returns"));

section("Cancel a purchase");
const p2 = await buy({ items: [{ productId: soap._id, qty: 3, cost: 100 }] });
eq(await stock(soap), 3, "soap 3");
const v = await owner.call(`/api/purchases/${p2._id}/void`, { body: { reason: "Entered twice" } });
eq(v.status, "void", "purchase cancelled");
eq(v.voidReason, "Entered twice", "reason kept");
eq(await stock(soap), 0, "soap back to 0");
await owner.call(`/api/purchases/${p2._id}/void`, { body: {}, expect: 400 }).then((e) => ok(/already cancelled/.test(e.error), "cannot cancel twice"));
await ret(p2, {}, 400).then((e) => ok(/cancelled/.test(e.error), "cannot return a cancelled purchase"));
const before = await bal();
const p3 = await buy({ supplierId: sup._id, amountPaid: 50, items: [{ productId: soap._id, qty: 2, cost: 100 }] });
eq(await bal(), before + 150, "payable +150");
await owner.call(`/api/purchases/${p3._id}/void`, { body: {} });
eq(await bal(), before, "cancel removes the unpaid 150 from khata");
const led = (await owner.call(`/api/parties/${sup._id}`)).ledger.filter((e) => e.refNo === p3.purchaseNo);
ok(led.some((e) => e.kind === "adjustment" && e.amount === -200) && led.some((e) => e.kind === "reversal" && e.amount === 50), "khata shows purchase and payment cancelled");
const p4 = await buy({ items: [{ productId: soap._id, qty: 5, cost: 100 }] });
await owner.call("/api/sales", { body: { items: [{ productId: soap._id, qty: 3 }], paymentMethod: "cash" } });
await owner.call(`/api/purchases/${p4._id}/void`, { body: {}, expect: 400 }).then((e) => ok(/Only 2 pcs of Soap/.test(e.error), "cannot cancel when stock was sold: " + e.error));
r = await ret(p4, {}, 400).then((e) => ok(/Only 2/.test(e.error), "return-all also checks stock"));
r = await ret(p4, { items: [{ index: 0, qty: 2 }] });
eq(r.settlement, "cash", "no-supplier purchase returns are cash back");
await ret(p4, { items: [{ index: 0, qty: 1 }], settlement: "khata" }, 400).then((e) => ok(/no supplier/.test(e.error), "no khata without supplier"));

section("Legacy purchase without status");
const p5 = await buy({ items: [{ productId: soap._id, qty: 1, cost: 100 }] });
await (await db()).collection("purchases").updateOne({ _id: oid(p5._id) }, { $unset: { status: 1, returnSeq: 1, returnedTotal: 1 } });
eq((await owner.call(`/api/purchases/${p5._id}/void`, { body: {} })).status, "void", "old purchase can be cancelled");

section("Reports and cash drawer");
const today = new Intl.DateTimeFormat("en-CA", { timeZone: "Asia/Karachi" }).format(new Date());
const list = await owner.call(`/api/purchases?from=${today}&to=${today}`);
const rets = await owner.call(`/api/purchase-returns?from=${today}&to=${today}`);
eq(rets.length, 8, "8 returns listed (rice 2, oil 5, soap 1)");
const rep = await owner.call(`/api/reports?from=${today}&to=${today}`);
const active = list.filter((x) => x.status !== "void").reduce((a, x) => a + x.total, 0);
const returned = rets.reduce((a, x) => a + x.total, 0);
eq(rep.summary.purchaseReturns, returned, "report: returned to suppliers");
eq(rep.summary.purchases, r2(active - returned), "report: purchases net of returns and cancellations");
const cur = await owner.call("/api/shifts/current");
eq(cur.summary.supplierCashBack, 200 + 200, "drawer: cash back from suppliers (200 rice + 200 soap)");
eq(cur.summary.purchasesPaid, list.filter((x) => x.status !== "void").reduce((a, x) => a + x.amountPaid, 0), "drawer: cancelled purchases not counted as paid");
ok(cur.summary.cashFlow.some((x) => x.label === "Cash back from suppliers" && x.amount === 400), "drawer cash flow line");
const backup = await owner.call("/api/backup");
eq(backup.data.purchaseReturns.length, rets.length, "purchase returns in backup");
await owner.call("/api/restore", { body: { backup, confirm: "Stock Mart" } });
const p6 = await buy({ items: [{ productId: soap._id, qty: 1, cost: 100 }] });
r = await ret(p6, {});
eq(r.returnNo, `PRN-${String(rets.length + 1).padStart(6, "0")}`, "numbering continues after restore");
eq((await owner.raw("/purchases")).status, 200, "purchases page");

await done();
